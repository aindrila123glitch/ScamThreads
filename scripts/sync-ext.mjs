// Synchronizes lexical phishing rules and brand definitions into extension/lexical.js
import { readFile, writeFile } from 'node:fs/promises';

const local = name => new URL(name, import.meta.url);

async function sync() {
  const brandsJson = await readFile(local('../brands-builtin.json'), 'utf8');
  const lexicalCode = await readFile(local('../lexical.mjs'), 'utf8');

  // Strip ESM export statements and wrap for service worker compatibility
  const cleanCode = lexicalCode
    .replace(/^export\s+/gm, '')
    .replace(/\/\*[\s\S]*?\*\/|([^:]|^)\/\/.*$/gm, '$1'); // strip comments if needed

  const output = `// Auto-generated by scripts/sync-ext.mjs - DO NOT EDIT DIRECTLY
const BUILTIN_BRANDS = ${brandsJson.trim()};

${cleanCode}

// Global exposure for MV3 worker.js and content scripts
const _g = typeof globalThis !== 'undefined' ? globalThis : typeof window !== 'undefined' ? window : self;
_g.parseLoose = parseLoose;
_g.lexicalSignals = lexicalSignals;
_g.getRegisteredDomain = getRegisteredDomain;
_g.BUILTIN_BRANDS = BUILTIN_BRANDS;
`;

  await writeFile(local('../extension/lexical.js'), output);
  console.log('Successfully synced lexical.mjs and brands-builtin.json -> extension/lexical.js');
}

sync().catch(err => {
  console.error('sync-ext failed:', err);
  process.exitCode = 1;
});

